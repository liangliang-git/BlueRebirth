def main() -> int:
    repo_root = Path(__file__).resolve().parents[1]
    client_root = Path(r"E:\BlueOath Rebirth")
    config_root = client_root / "blueoath" / "blueoath_Data" / "StreamingAssets" / "config"
    work_root = client_root / "技能与突破汉化"
    source_dir, decoded_dir = work_root / "source-db", work_root / "decoded-json"
    translated_dir, compiled_dir = work_root / "translated-json", work_root / "compiled-db"
    backup_dir = work_root / "backup" / "client-config"
    for directory in (source_dir, decoded_dir, translated_dir, compiled_dir, backup_dir):
        directory.mkdir(parents=True, exist_ok=True)

    helper = load_module(repo_root, "blueoath_first_batch", repo_root / "tools" / "localize-first-batch.py")
    translator = helper.load_helpers(repo_root).load_local_translator(repo_root)
    summary: dict[str, dict[str, int]] = {}
    mappings: list[dict[str, Any]] = []

    for file_name, fields in TARGET_FIELDS.items():
        current = config_root / file_name
        source_copy = source_dir / file_name
        compiled = compiled_dir / file_name
        if not current.exists():
            raise FileNotFoundError(current)
        if not source_copy.exists():
            shutil.copy2(current, source_copy)
        shutil.copy2(current, backup_dir / file_name)
        shutil.copy2(source_copy, compiled)

        con = sqlite3.connect(source_copy)
        rows = con.execute("select id,indexid,jsonbytes from DBObject order by id").fetchall()
        con.close()
        decoded, translated_rows, updates = [], [], []
        stats = {"rows": 0, "valid_json": 0, "text_fields": 0, "changed": 0, "jp_before": 0, "jp_after": 0, "integrity_ok": 0}
        for row_id, index_id, raw in rows:
            row_id, index_id = str(row_id), "" if index_id is None else str(index_id)
            payload = decode(bytes(raw))
            stats["rows"] += 1
            if payload is None:
                decoded.append({"id": row_id, "indexid": index_id, "json": None})
                translated_rows.append({"id": row_id, "indexid": index_id, "json": None})
                continue
            stats["valid_json"] += 1
            new_payload = payload
            if isinstance(payload, dict):
                for field in fields:
                    original = payload.get(field)
                    if not isinstance(original, str) or not original.strip():
                        continue
                    stats["text_fields"] += 1
                    stats["jp_before"] += int(bool(JP_RE.search(original)))
                    mapped = translate_name(original, helper, translator) if field == "skill_name" else translate_text(original, file_name, field, helper, translator)
                    stats["jp_after"] += int(bool(JP_RE.search(mapped)))
                    if tokens(original) != tokens(mapped):
                        raise ValueError(f"runtime token mismatch: {file_name}:{row_id}:{field}")
                    if mapped != original:
                        if new_payload is payload:
                            new_payload = dict(payload)
                        new_payload[field] = mapped
                        stats["changed"] += 1
                        mappings.append({"file": file_name, "id": row_id, "field": field, "original": original, "translated": mapped})
            decoded.append({"id": row_id, "indexid": index_id, "json": payload})
            translated_rows.append({"id": row_id, "indexid": index_id, "json": new_payload})
            if new_payload is not payload:
                updates.append((row_id, encode(new_payload)))

        dump(decoded_dir / f"{file_name}.json", decoded)
        dump(translated_dir / f"{file_name}.json", translated_rows)
        out = sqlite3.connect(compiled)
        for row_id, encoded in updates:
            out.execute("update DBObject set jsonbytes=? where id=?", (sqlite3.Binary(encoded), row_id))
        out.commit()
        if out.execute("pragma integrity_check").fetchone()[0] != "ok":
            out.close()
            raise RuntimeError(f"{file_name}: integrity check failed")
        out.close()
        stats["integrity_ok"] = 1
        summary[file_name] = stats

    dump(work_root / "translation-map.json", mappings)
    dump(work_root / "run-summary.json", {"files": summary, "field_scope": {k: sorted(v) for k, v in TARGET_FIELDS.items()}, "network_translation": False, "ship_names_excluded": True, "xor_key": 0x55})

    residual = sum(v["jp_after"] for v in summary.values())
    if residual:
        raise RuntimeError(f"model translation incomplete: {residual} Japanese target fields remain; client not modified")

    # Deploy compiled files into client config.
    for file_name in TARGET_FIELDS:
        shutil.copy2(compiled_dir / file_name, config_root / file_name)
    print(json.dumps({"work_root": str(work_root), "files": summary, "changed": sum(v["changed"] for v in summary.values()), "jp_after": residual, "translation_source": "current-model-authored-data-only"}, ensure_ascii=False))
    return 0


